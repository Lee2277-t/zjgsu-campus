// scripts/test-release-hardening.cjs —— 上线前安全与数据一致性守卫
const fs = require('fs');
const path = require('path');
const readCloudSource = require('./cloud-source.cjs');
const root = path.resolve(__dirname, '..');
const M = path.join(root, 'miniprogram', 'zjgsu-campus');
const read = (p) => fs.readFileSync(path.join(M, p), 'utf8');
let pass = 0; let fail = 0;
function ok(name, cond, detail) { if (cond) { pass += 1; return; } fail += 1; console.log('  ✗ ' + name + (detail ? ' | ' + detail : '')); }
function safeJson(p) { try { return JSON.parse(read(p)); } catch (e) { ok('JSON 可解析: ' + p, false, e.message); return null; } }
const user = read('utils/user.js');
const cf = readCloudSource();
const forum = read('utils/store-forum.js');
const chat = read('utils/chat.js');
const sync = read('utils/store-sync.js');
const app = read('app.js');
const profile = read('pages/user/profile/profile.js');
const sitemap = safeJson('sitemap.json');
const appJson = safeJson('app.json');
const cfg = safeJson('cloudfunctions/user/config.json');
const initBody = (user.match(/function initUser\(\) \{[\s\S]*?\n\}/) || [''])[0];
ok('资料启动只读云端、不用空缓存覆盖', /call\('getProfile'/.test(initBody) && !/upsertProfile/.test(initBody));
ok('资料写入有本机 dirty 标记', /profileDirty/.test(user) && /zjgsu_profile_dirty/.test(user));
ok('资料保存失败不再返回成功', /localOnly: true/.test(user) && /云端没同步，资料只保存在本机/.test(user));
ok('评论客户端带幂等 id', /function postComment\(postId, content, images, reply, id\)/.test(user) && /id: String\(id \|\| ''\)/.test(user));
ok('评论失败不再返回 ok:true', /saved: false, local: true, msg: '云端没响应，评论先留在本机'/.test(user));
ok('云端评论接受客户端 id', /const commentId =/.test(cf) && /id: commentId/.test(cf));
ok('评论成功后用服务端对象回写本地', /Object\.assign\(\{\}, c, r\.comment/.test(forum));
ok('内容编辑接口限制为评价且不改计数', /该接口只允许修改课程评价/.test(cf) && !/\['likes', 'status', 'hiddenReason'\]/.test(cf));
ok('评价编辑有服务端内容审核', /async function patchContent[\s\S]{0,1200}await guard\(text\)/.test(cf));
ok('帖子编辑失败会回失败', /帖子没存住，再试一次/.test(cf));
ok('帖子编辑图片重新过审', /async function postEdit[\s\S]{0,1800}submitMediaCheck/.test(cf));
ok('发帖/编辑/留言发布前同步图片审核', /function checkImageRiskSync/.test(cf) && /const mediaErr = await imageGate\(imgs\)/.test(cf) && /const mediaErr = await imageGate\(images\)/.test(cf));
ok('imgSecCheck 权限已配置', cfg && cfg.permissions && cfg.permissions.openapi && cfg.permissions.openapi.indexOf('security.imgSecCheck') >= 0);
ok('媒体回执拒绝客户端伪造', /无权提交媒体审核回执/.test(cf));
ok('无 action 调用只接受 Timer 事件', /event\.Type === 'Timer'/.test(cf) && /if \(openid\) return \{ ok: false, msg: '未知操作' \}/.test(cf));
ok('种子写入默认关闭', /ALLOW_SEED !== '1'/.test(cf));
ok('资源文件限制在 resources 目录', /isCloudFileIn\(fileID, 'resources'\)/.test(cf) && /isCloudFileIn\(rec\.fileID, 'resources'\)/.test(cf));
ok('资源删除同步清理云文件', /cloud\.deleteFile\(\{ fileList: \[rec\.fileID\] \}\)/.test(cf));
ok('封禁覆盖编辑与状态接口', /'postEdit'/.test(cf) && /'patchContent'/.test(cf) && /'setStatus'/.test(cf));
ok('作者不能自行下架或删除', /只有审核员能下架或删除内容/.test(cf));
ok('注销清理新增私有集合', ['COL_NOTIFIES','COL_VIEWS','COL_DRAFTS','COL_COMMENT_VOTES','COL_MEDIA'].every((x) => cf.indexOf(x) >= 0));
ok('注销清理分页且不再只删前 100 条', /const rmAll =/.test(cf) && /for \(let page = 0; page < 100; page \+= 1\)/.test(cf));
ok('启动检测账号切换与注销', /clearAccountCache/.test(app) && /zjgsu_openid/.test(app) && /zjgsu_account_deleted/.test(app));
ok('资料页在云端读取前要求隐私授权', /privacy\.requireIfNeeded/.test(profile));
ok('私信云端失败不再假成功', /saved: false, local: true, msg: '云端没响应，消息只在本机'/.test(chat));
ok('分页同步失败不覆盖完整缓存', /if \(!res \|\| !res\.data\) return null;/.test(sync));
ok('sitemap 禁止私人页面索引', sitemap && sitemap.rules.some((r) => r.action === 'disallow' && String(r.page).indexOf('pages/user') >= 0));
ok('媒体审核每 10 分钟兜底', cfg && cfg.triggers.some((t) => t.name === 'mediaAuditSweep' && t.type === 'timer'));
ok('用户中心已移入分包', appJson && appJson.subPackages.some((p) => p.root === 'pages/user' && p.pages.indexOf('chat/chat') >= 0) && !appJson.pages.some((p) => p.indexOf('pages/user/') === 0));
console.log('\n上线硬化检查：' + (fail ? ('失败 ' + fail) : ('通过 ' + pass)));
if (fail) process.exit(1);